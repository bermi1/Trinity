// Opens a branded, print-ready document in a new tab and starts the browser's
// print dialog, where people can print it or "Save as PDF".

const esc = s => String(s ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);

const CSS = `
  *{box-sizing:border-box}body{margin:0;font-family:Manrope,system-ui,sans-serif;color:#17152A;-webkit-print-color-adjust:exact;print-color-adjust:exact}
  .page{max-width:820px;margin:0 auto;padding:40px 44px}
  header{display:flex;justify-content:space-between;align-items:flex-end;border-bottom:3px solid #2B1459;padding-bottom:18px;margin-bottom:26px}
  .brand{display:flex;align-items:center;gap:12px}.brand b{color:#2B1459;letter-spacing:.24em;font-size:13px}.brand span{display:block;color:#8A7239;font:600 9px 'IBM Plex Mono',monospace;letter-spacing:.3em;margin-top:3px}
  .meta{text-align:right;font-size:11px;color:#6E6A7C;line-height:1.6}
  .kicker{font:600 11px 'IBM Plex Mono',monospace;letter-spacing:.16em;color:#8A7239}
  h1{margin:6px 0 4px;font-size:26px;letter-spacing:-.02em}p.sub{margin:0 0 22px;color:#6E6A7C;font-size:13px}
  dl{display:grid;grid-template-columns:170px 1fr;gap:8px 16px;margin:0 0 22px;font-size:13px}dt{color:#6E6A7C}dd{margin:0;font-weight:600}
  table{width:100%;border-collapse:collapse;font-size:12px;margin-bottom:22px}th{text-align:left;background:#F4F1FA;color:#2B1459;font-size:10.5px;letter-spacing:.06em;text-transform:uppercase;padding:9px 10px}
  td{padding:9px 10px;border-bottom:1px solid #EDE9F3}tr:nth-child(even) td{background:#FCFBFE}
  .total{display:flex;justify-content:flex-end;gap:24px;font-size:15px;font-weight:700;color:#2B1459;margin-bottom:22px}
  footer{margin-top:34px;padding-top:14px;border-top:1px solid #E8E4EF;font-size:10.5px;color:#6E6A7C;display:flex;justify-content:space-between}
  .bar{position:sticky;top:0;background:#1D103D;color:#fff;padding:10px 16px;display:flex;justify-content:space-between;align-items:center;font-size:13px}
  .bar button{border:none;border-radius:8px;padding:8px 14px;font-weight:700;background:#B49A5A;color:#1D103D;cursor:pointer}
  @media print{.bar{display:none}.page{padding:0}@page{margin:16mm}}`;

const LOGO = '<svg width="26" height="30" viewBox="138 118 176 196" fill="none" stroke="#B49A5A" stroke-width="15" stroke-linecap="round" stroke-linejoin="round"><path d="M153 130 V186 Q153 214 182 214 H274 Q304 214 284 240 L214 298 Q205 306 196 298 L168 248"/><path d="M201 158 H266"/></svg>';

// doc: { kicker, title, sub, ref, fields: [[label, value]], table: { head: [], rows: [[]] }, total: [label, value], note }
export function renderDocument(doc) {
  const date = new Date().toLocaleDateString('en-GB', { day: '2-digit', month: 'long', year: 'numeric' });
  const fields = doc.fields?.length ? '<dl>' + doc.fields.map(([k, v]) => `<dt>${esc(k)}</dt><dd>${esc(v)}</dd>`).join('') + '</dl>' : '';
  const table = doc.table ? '<table><thead><tr>' + doc.table.head.map(h => `<th>${esc(h)}</th>`).join('') + '</tr></thead><tbody>' +
    doc.table.rows.map(r => '<tr>' + r.map(c => `<td>${esc(c)}</td>`).join('') + '</tr>').join('') + '</tbody></table>' : '';
  const total = doc.total ? `<div class="total"><span>${esc(doc.total[0])}</span><span>${esc(doc.total[1])}</span></div>` : '';
  return `<!doctype html><html><head><meta charset="utf-8"><title>${esc(doc.ref || doc.title)}</title>
<link href="https://fonts.googleapis.com/css2?family=Manrope:wght@400;600;700;800&family=IBM+Plex+Mono:wght@500;600&display=swap" rel="stylesheet"><style>${CSS}</style></head>
<body><div class="bar"><span>${esc(doc.title)}</span><button onclick="print()">Print / Save as PDF</button></div><div class="page">
<header><div class="brand">${LOGO}<div><b>TRINITY MARK</b><span>SOLUTIONS LTD</span></div></div>
<div class="meta">Dar es Salaam, Tanzania<br>${esc(date)}${doc.ref ? '<br>Ref. ' + esc(doc.ref) : ''}</div></header>
<span class="kicker">${esc(doc.kicker || '')}</span><h1>${esc(doc.title)}</h1>${doc.sub ? `<p class="sub">${esc(doc.sub)}</p>` : ''}
${fields}${table}${total}${doc.note ? `<p style="font-size:12.5px;line-height:1.6;color:#3D3950">${esc(doc.note)}</p>` : ''}
<footer><span>Trinity Mark Solutions Ltd · Ideas. Events. Brands. Real Impact.</span><span>Generated by Trinity Mark 360</span></footer>
</div><script>document.fonts&&document.fonts.ready.then(()=>setTimeout(()=>print(),300))</script></body></html>`;
}

// Returns false when the browser blocked the new tab.
export function printDocument(doc) {
  const w = window.open('', '_blank');
  if (!w) return false;
  w.document.open();
  w.document.write(renderDocument(doc));
  w.document.close();
  return true;
}
